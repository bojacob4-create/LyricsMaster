_FONT_BOLD = "bold"
_FONT_REG = "regular"
_FONT_FAMILY = "manrope"  # or "inter"
_DEJAVU_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
