"""Round 57: Share Card — branded story-format lyric cards (v4 design).

A song-card button ("Share Card") renders a signature @MGLyricsbot image:
1080x1350 portrait (4:5), colorful dark template tinted with TWO colors pulled
from the album art (dominant + vibrant accent), lyric excerpt in bold centered
Manrope (Inter available), artist/title right under it, QR code floating light
on the left with an invisible dark halo for scan contrast, album artwork on
the right, and a "Generated by @MGLyricsbot" footer.

The QR deep-links to that exact song card in the bot
(t.me/MGLyricsbot?start=share_<token>).
"""
